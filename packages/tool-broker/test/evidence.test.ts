import test from 'node:test';
import assert from 'node:assert/strict';
import { memoryRetrievalEvidence, pageEvidence, redactEvidenceText, screenshotEvidence } from '../src/evidence.js';

test('page evidence comes from the tool capture and drops secrets, queries and excess text', () => {
  const captured = pageEvidence({ url: 'https://user:secret@internal.example.com/path?token=abc#session', capturedAt: '2026-11-19T01:02:03.000Z', runId: 'run', stepId: 'step', body: `欢迎\npassword: hunter2\nAuthorization: Bearer very-secret\n${'正文'.repeat(100_000)}`, maxBytes: 200 });
  assert.equal(captured.evidence_kind, 'page_capture');
  assert.equal(captured.provenance, 'tool_broker');
  assert.equal(captured.captured_at, '2026-11-19T01:02:03.000Z');
  assert.equal(captured.source_url, 'https://internal.example.com/path');
  assert.equal(captured.viewer_required, false);
  assert.equal(captured.truncated, true);
  assert.equal(JSON.stringify(captured).includes('hunter2'), false);
  assert.equal(JSON.stringify(captured).includes('very-secret'), false);
  const nested = pageEvidence({ url: 'https://example.com/start', capturedAt: '2026-11-19T01:02:03.000Z', runId: 'run', stepId: 'step', body: { url: 'https://login.example/callback?code=synthetic-auth-code&next=/home#token=synthetic-fragment', title: '业务标题' } });
  assert.equal(JSON.stringify(nested).includes('synthetic-auth-code'), false);
  assert.equal(JSON.stringify(nested).includes('synthetic-fragment'), false);
  assert.equal(JSON.stringify(nested).includes('业务标题'), true);
  assert.equal(nested.redacted, true);
  assert.equal(redactEvidenceText('cookie: session=abc').redacted, true);
});

test('screenshot evidence does not require a live viewer and memory evidence keeps references only', () => {
  const shot = screenshotEvidence({ url: 'https://example.com/a?x=1', capturedAt: '2026-11-19T01:02:03.000Z', runId: 'run', stepId: 'step', bytes: Buffer.from('jpeg'), width: 10, height: 12 });
  assert.equal(shot.viewer_required, false);
  assert.equal(shot.captured_at, '2026-11-19T01:02:03.000Z');
  assert.equal(JSON.stringify(shot).includes('jpeg'), false);
  const memory = memoryRetrievalEvidence({ generatedAt: '2026-11-19T01:02:03.000Z', runId: 'run', stepId: 'step', query: '入口', scope: { project: 'alpha', sites: ['example.com'] }, hits: [{ id: 'm1', version: 3, title: '入口', site: 'example.com', status: 'verified', content: '不应进入证据的公司全文' }] });
  assert.equal(JSON.stringify(memory).includes('不应进入证据'), false);
  assert.equal((memory.hits as { id: string; version: number }[])[0].version, 3);
  const stale = memoryRetrievalEvidence({ generatedAt: '2026-11-19T02:00:00.000Z', runId: 'run', stepId: 'step', query: '入口', scope: null, hits: [{ id: 'm1', version: 3, status: 'verified', fresh: false, stale: true, stale_reason: 'offline', observed_at: '2026-11-19T00:00:00.000Z', content: '旧正文' }] });
  assert.equal(stale.fresh, false);
  assert.equal(stale.acceptable_as_current, false);
  assert.equal((stale.hits as { observed_at: string; status: string }[])[0].observed_at, '2026-11-19T00:00:00.000Z');
  assert.equal(JSON.stringify(stale).includes('旧正文'), false);
  const observed = '2026-11-19T00:00:00.000Z';
  const emptyTtl = memoryRetrievalEvidence({ generatedAt: '2026-11-19T02:00:00.000Z', runId: 'run', stepId: 'step', query: '入口', scope: null, hits: { items: [], stale: true, fresh: false, stale_reason: 'ttl', observed_at: observed } });
  assert.equal(emptyTtl.stale, true);
  assert.equal(emptyTtl.fresh, false);
  assert.equal(emptyTtl.acceptable_as_current, false);
  assert.equal(emptyTtl.stale_reason, 'ttl');
  assert.equal(emptyTtl.observed_at, observed);
  assert.equal(typeof emptyTtl.generated_at, 'string');
  assert.ok(emptyTtl.generated_at);
  assert.equal('retrieved_at' in emptyTtl, true);
  const emptyOffline = memoryRetrievalEvidence({ generatedAt: '2026-11-19T03:00:00.000Z', runId: 'run', stepId: 'step', query: '入口', scope: null, hits: { items: [], stale: true, fresh: false, stale_reason: 'offline', observed_at: observed, retrieved_at: '2026-11-19T01:00:00.000Z', generated_at: '2026-11-19T03:00:00.000Z' } });
  assert.equal(emptyOffline.fresh, false);
  assert.equal(emptyOffline.stale, true);
  assert.equal(emptyOffline.stale_reason, 'offline');
  assert.equal(emptyOffline.observed_at, observed);
  assert.equal(emptyOffline.retrieved_at, '2026-11-19T01:00:00.000Z');
  assert.equal(emptyOffline.generated_at, '2026-11-19T03:00:00.000Z');
  assert.notEqual(emptyOffline.observed_at, emptyOffline.retrieved_at);
  assert.notEqual(emptyOffline.retrieved_at, emptyOffline.generated_at);
  const bareEmpty = memoryRetrievalEvidence({ generatedAt: '2026-11-19T02:00:00.000Z', runId: 'run', stepId: 'step', query: '入口', scope: null, hits: [] });
  assert.equal(bareEmpty.fresh, true);
  assert.equal(bareEmpty.stale, false);
  const uncertain = pageEvidence({ url: 'https://later.example/after?token=abc', capturedAt: '2026-11-19T01:02:03.000Z', runId: 'run', stepId: 'step', body: 'first-body', sourceUncertain: true, sourceUncertainReason: '页面在捕获期间发生跳转，不能确定正文对应的网址' });
  assert.equal(uncertain.source_uncertain, true);
  assert.equal(uncertain.source_url, null);
  assert.equal(uncertain.fresh, false);
  assert.equal(uncertain.stale, true);
  assert.equal(JSON.stringify(uncertain).includes('later.example'), false);
  assert.equal(JSON.stringify(uncertain).includes('token=abc'), false);
  const uncertainShot = screenshotEvidence({ url: 'https://later.example/after', capturedAt: '2026-11-19T01:02:03.000Z', runId: 'run', stepId: 'step', bytes: Buffer.from('jpeg'), width: 10, height: 12, sourceUncertain: true });
  assert.equal(uncertainShot.source_uncertain, true);
  assert.equal(uncertainShot.source_url, null);
  assert.equal(uncertainShot.fresh, false);
  assert.equal(uncertainShot.stale, true);
  assert.equal(JSON.stringify(uncertainShot).includes('jpeg'), false);
  assert.equal(JSON.stringify(uncertainShot).includes('later.example'), false);
  assert.equal(JSON.stringify(uncertainShot).includes('人工打开图片'), true);
});

test('a missing or non-http source is stale and uncertain, while a stable https url stays fresh and redacted', () => {
  const capturedAt = '2026-11-19T01:02:03.000Z';
  for (const url of ['', 'about:blank', 'file:///tmp/page', null]) {
    const page = pageEvidence({ url, capturedAt, runId: 'run', stepId: 'step', body: '正文' });
    assert.equal(page.source_uncertain, true);
    assert.equal(page.fresh, false);
    assert.equal(page.stale, true);
    assert.equal(page.source_url, null);
    assert.equal(typeof page.source_uncertain_reason, 'string');
    assert.ok(page.source_uncertain_reason);
    const shot = screenshotEvidence({ url, capturedAt, runId: 'run', stepId: 'step', bytes: Buffer.from('jpeg'), width: 8, height: 8 });
    assert.equal(shot.source_uncertain, true);
    assert.equal(shot.fresh, false);
    assert.equal(shot.stale, true);
    assert.equal(shot.source_url, null);
    assert.equal(JSON.stringify(shot).includes('jpeg'), false);
  }
  const page = pageEvidence({ url: 'https://user:secret@example.com/path?token=abc&code=1#session', capturedAt, runId: 'run', stepId: 'step', body: '稳定正文' });
  assert.equal(page.source_url, 'https://example.com/path');
  assert.equal(page.source_uncertain, false);
  assert.equal(page.fresh, true);
  assert.equal(page.stale, false);
  assert.equal(JSON.stringify(page).includes('secret'), false);
  assert.equal(JSON.stringify(page).includes('token=abc'), false);
  const shot = screenshotEvidence({ url: 'https://user:secret@example.com/path?ticket=abc#x', capturedAt, runId: 'run', stepId: 'step', bytes: Buffer.from('jpeg'), width: 8, height: 8 });
  assert.equal(shot.source_url, 'https://example.com/path');
  assert.equal(shot.source_uncertain, false);
  assert.equal(shot.fresh, true);
  assert.equal(shot.stale, false);
  assert.equal(JSON.stringify(shot).includes('secret'), false);
  assert.equal(JSON.stringify(shot).includes('ticket=abc'), false);
});
